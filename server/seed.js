'use strict';
// Демо-наповнення при першому запуску: приклад курсу, класу та учнів.
const { hashPw, genPassword } = require('./util');

const CRITERIA = `## Як оцінюється практична робота (12-бальна шкала)

| Рівень | Бали | Що це означає |
|---|---|---|
| Початковий | 1–3 | Виконано окремі кроки лише з допомогою вчителя або однокласника |
| Середній | 4–6 | Виконано більшість кроків за інструкцією, є помилки, результат неповний |
| Достатній | 7–9 | Усі кроки виконано самостійно за інструкцією, результат відповідає зразку |
| Високий | 10–12 | Робота виконана самостійно й акуратно; учень пояснює, **що** і **чому** робив, може застосувати вміння в новій ситуації |

**Що впливає на оцінку**
- самостійність виконання (за клавіатурою сам чи спостерігав);
- точність результату (скриншот / файл відповідає завданню);
- відповідь на запитання вчителя «покажи, як ти це зробив»;
- охайність і дотримання правил роботи за комп'ютером.

**Пропустив урок?** Ти можеш виконати практичну вдома або на наступному уроці — система зарахує її. Оцінку виставляє вчитель.`;

module.exports = function seed({ get, run }) {
  const course = run('INSERT INTO courses(title,description,criteria) VALUES(?,?,?)',
    'Інформатика. 6 клас',
    'Вчимося працювати з інформацією: створювати документи, презентації та перші програми.',
    CRITERIA).lastInsertRowid;

  const u1 = run('INSERT INTO units(course_id,position,title,goal,why) VALUES(?,?,?,?,?)', course, 1,
    'Текстовий редактор',
    'Створювати та оформлювати текстові документи: шрифти, абзаци, списки, зображення.',
    'Реферати, листи, оголошення, резюме — усе це текстові документи. Охайно оформлений документ легше читати, і тебе сприймають серйозніше.').lastInsertRowid;
  const u2 = run('INSERT INTO units(course_id,position,title,goal,why) VALUES(?,?,?,?,?)', course, 2,
    'Алгоритми та програмування (Scratch)',
    'Складати алгоритми з повтореннями та розгалуженнями і реалізовувати їх у Scratch.',
    'Алгоритмічне мислення допомагає розбивати велику задачу на маленькі кроки — це корисно не тільки в програмуванні.').lastInsertRowid;

  const L = (unit, pos, title, objectives, why, sc, theory, hw, steps, questions) => {
    const lid = run(`INSERT INTO lessons(unit_id,position,title,objectives,why,success_criteria,theory,homework)
      VALUES(?,?,?,?,?,?,?,?)`, unit, pos, title, objectives, why, sc, theory, hw).lastInsertRowid;
    steps.forEach((t, i) => run('INSERT INTO steps(lesson_id,position,text) VALUES(?,?,?)', lid, i + 1, t));
    questions.forEach(q => run('INSERT INTO questions(lesson_id,text,options,correct,explain) VALUES(?,?,?,?,?)',
      lid, q[0], JSON.stringify(q[1]), q[2], q[3] || ''));
    return lid;
  };

  L(u1, 1, 'Форматування шрифту',
    'змінювати шрифт, розмір, колір і накреслення тексту',
    'Заголовки й виділення допомагають читачеві швидко знайти головне.',
    'Я можу змінити шрифт і розмір тексту\nЯ можу зробити текст жирним, курсивним, підкресленим\nЯ можу пояснити, навіщо виділяти заголовок',
    'Шрифт — це **вигляд** літер. Основні властивості: *гарнітура* (назва шрифту), *розмір* (у пунктах), *накреслення* (жирний, курсив, підкреслений) і *колір*.\n\nКомбінації клавіш: `Ctrl+B` — жирний, `Ctrl+I` — курсив, `Ctrl+U` — підкреслений.',
    'Оформи 3–4 речення про своє хобі: заголовок 16 пт жирним, текст 12 пт.',
    ['Відкрий текстовий редактор (LibreOffice Writer або Word).',
      'Набери заголовок «Моє улюблене заняття» і натисни **Enter**.',
      'Набери 2–3 речення про своє хобі.',
      'Виділи заголовок мишею (затисни ліву кнопку та протягни).',
      'Встанови для заголовка шрифт **Arial**, розмір **16** і натисни `Ctrl+B`.',
      'Виділи основний текст і встанови розмір **12**.',
      'Зміни колір одного слова, яке хочеш підкреслити.',
      'Збережи документ у папку **Мої документи** з назвою `Прізвище_хобі`.'],
    [['Яке поєднання клавіш робить текст жирним?', ['Ctrl+B', 'Ctrl+I', 'Ctrl+U', 'Ctrl+S'], 0, 'B — від англ. Bold (жирний).'],
      ['Що таке розмір шрифту?', ['Колір літер', 'Висота літер у пунктах', 'Назва шрифту', 'Відстань між рядками'], 1],
      ['Що потрібно зробити ПЕРЕД тим, як змінити шрифт частини тексту?', ['Зберегти файл', 'Виділити текст', 'Закрити програму', 'Натиснути Enter'], 1]]);

  L(u1, 2, 'Списки та зображення в документі',
    'створювати нумеровані й марковані списки та вставляти зображення',
    'Список — найзручніший спосіб записати інструкцію або перелік. Зображення робить документ наочним.',
    'Я можу створити нумерований і маркований список\nЯ можу вставити зображення та змінити його розмір',
    'Нумерований список — коли **важливий порядок** (інструкція). Маркований — коли порядок неважливий (перелік речей).',
    'Склади нумерований список «Як приготувати бутерброд» (5–7 кроків).',
    ['Відкрий документ з минулого уроку `Прізвище_хобі`.',
      'Під текстом напиши «Що мені потрібно:» і створи **маркований** список з 3 пунктів.',
      'Напиши «Як я цим займаюся:» і створи **нумерований** список з 3 кроків.',
      'Вставка → Зображення: встав малюнок з папки **Картинки**.',
      'Зменш зображення, потягнувши за кутовий маркер (щоб не спотворити пропорції).',
      'Збережи документ (`Ctrl+S`).'],
    [['Коли краще використати нумерований список?', ['Коли важливий порядок', 'Для переліку покупок', 'Для заголовка', 'Ніколи'], 0],
      ['Як змінити розмір зображення, не спотворивши його?', ['Тягнути за бічний маркер', 'Тягнути за кутовий маркер', 'Натиснути Delete', 'Змінити шрифт'], 1]]);

  L(u2, 1, 'Перший проєкт у Scratch: рух спрайта',
    'керувати рухом спрайта за допомогою блоків руху та подій',
    'Scratch — це конструктор програм: ти бачиш результат одразу. Так працюють і справжні ігри.',
    'Я можу запустити програму за подією «коли натиснуто прапорець»\nЯ можу змусити спрайт рухатися та повертатися\nЯ можу пояснити, що робить кожен блок у моїй програмі',
    'Програма в Scratch складається з **блоків**. Подія (жовті блоки) запускає скрипт, блоки **Руху** (сині) переміщують спрайт.',
    'Зроби, щоб кіт малював квадрат (підказка: 4 рази «перемістити» і «поворот на 90°»).',
    ['Відкрий Scratch (scratch.mit.edu або програму Scratch Desktop).',
      'Перетягни блок **«коли натиснуто 🏁»** з категорії *Події*.',
      'Під нього приєднай **«перемістити на 10 кроків»** і зміни 10 на **100**.',
      'Додай блок **«поворот ↻ на 15 градусів»** і зміни на **90**.',
      'Натисни зелений прапорець і подивися, що робить кіт.',
      'Додай блок **«чекати 1 секунд»** між рухом і поворотом.',
      'Збережи проєкт: Файл → Зберегти на комп\'ютер, назва `Прізвище_рух`.'],
    [['Який блок запускає програму в Scratch?', ['коли натиснуто прапорець', 'перемістити на 10 кроків', 'чекати 1 секунд', 'сказати Привіт'], 0],
      ['На скільки градусів треба повернути спрайт, щоб намалювати квадрат?', ['45', '90', '180', '360'], 1]]);

  const cls = run('INSERT INTO classes(name,course_id) VALUES(?,?)', '6-А', course).lastInsertRowid;
  const names = ['Андрієнко Марія', 'Бондар Олег', 'Ковальчук Ірина', 'Мельник Артем', 'Шевченко Софія', 'Ткаченко Максим'];
  const { translit } = require('./util');
  names.forEach(n => {
    const pw = genPassword();
    let login = translit(n.split(' ')[0]);
    if (get('SELECT id FROM users WHERE login=?', login)) login += Math.floor(Math.random() * 90 + 10);
    run("INSERT INTO users(role,name,login,pw_hash,pw_plain,class_id) VALUES('student',?,?,?,?,?)", n, login, hashPw(pw), pw, cls);
  });
};
